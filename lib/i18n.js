/**
 * Returns translation string by key and language code.
 * Falls back to English if key or language is missing.
 * @param {string} langCode
 * @param {string} key
 * @param {Object} [params]
 * @returns {string}
 */
function t(langCode, key, params = {}) {
  const code = (langCode || "en").toLowerCase();
  const dict = TRANSLATIONS[code] || TRANSLATIONS.en;
  let text = dict[key] || TRANSLATIONS.en[key] || key;

  for (const [pKey, pVal] of Object.entries(params)) {
    text = text.replace(new RegExp(`\\{${pKey}\\}`, "g"), String(pVal));
  }

  return text;
}

/**
 * Gets human-readable language name for LLM system prompt.
 * e.g. "vi" -> "Vietnamese", "ja" -> "Japanese"
 * @param {string} langCode
 * @returns {string}
 */
function getLanguageName(langCode) {
  const found = SUPPORTED_LANGUAGES.find((l) => l.code === (langCode || "").toLowerCase());
  return found ? found.name : "English";
}

